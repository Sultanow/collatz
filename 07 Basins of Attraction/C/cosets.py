#!/usr/bin/env python3
"""Multiplicative filtration (Proposition 6 of the paper) against the measured basin shares.

Usage:  python3 cosets.py ../results/landscape/landscape_shares.csv [--predictions FILE]

For c coprime to 6, T(n) = n/2 or (3n+c)/2 is congruent to n/2 or 3n/2 modulo c, so the
coset of n modulo the subgroup H of (Z/cZ)^* generated by 2 and 3 is constant along every
orbit of an integer prime to c. Each coset is completely invariant and holds the share
1/[G:H] of the integers prime to c. For every map with index [G:H] > 1 the script prints
the measured share of every coset (sum of the relative shares of its primitive cycles),
lists the cycles that are alone in their coset (their share is then exactly 1/[G:H]), and,
with --predictions (predictions_D70.csv of predictor_eval.py), evaluates the backward-mass
predictor before and after normalising it within the cosets.
"""
import csv
import math
import sys
from collections import defaultdict


def subgroup(n, gens):
    H, todo = {1}, [1]
    while todo:
        x = todo.pop()
        for g in gens:
            y = x * g % n
            if y not in H:
                H.add(y)
                todo.append(y)
    return H


def structure(c):
    H = subgroup(c, (2, 3))
    phi = sum(1 for a in range(1, c) if math.gcd(a, c) == 1)
    return H, phi // len(H)


def coset_of(x, c, H):
    return min(x * h % c for h in H)


def metrics(groups, measured, predicted):
    logd, absd, top = [], [], 0
    for keys in groups.values():
        p = [predicted[k] for k in keys]
        m = [measured[k] for k in keys]
        logd += [abs(math.log(a / b)) for a, b in zip(p, m) if a > 0 and b > 0]
        absd += [abs(a - b) for a, b in zip(p, m)]
        top += max(range(len(keys)), key=lambda i: p[i]) == max(range(len(keys)), key=lambda i: m[i])
    logd.sort()
    return (f"median |log ratio| {logd[len(logd) // 2]:.3f}, 90% {logd[int(0.9 * len(logd))]:.3f}, "
            f"mean |share error| {sum(absd) / len(absd):.4f}, largest basin right {top}/{len(groups)}")


def main():
    argv = sys.argv[1:]
    if not argv:
        print(__doc__)
        return
    pred_file = None
    if "--predictions" in argv:
        i = argv.index("--predictions"); pred_file = argv[i + 1]; del argv[i:i + 2]
    rel = {}
    for r in csv.DictReader(open(argv[0])):
        if r["m"] == "1":
            rel[(int(r["c"]), int(r["cycle_min"]))] = float(r["rel_share"])
    maps = defaultdict(list)
    for k in rel:
        maps[k[0]].append(k)
    nontrivial, alone, worst, empty = 0, [], 0.0, []
    for c in sorted(maps):
        if c == 1:
            continue
        H, idx = structure(c)
        if idx == 1:
            continue
        nontrivial += 1
        cos = defaultdict(list)
        for k in maps[c]:
            cos[coset_of(k[1] % c, c, H)].append(k)
        if len(cos) < idx:
            empty.append(c)
        tot = sorted(sum(rel[k] for k in ks) for ks in cos.values())
        worst = max(worst, max(abs(t - 1 / idx) for t in tot))
        print(f"3x+{c}: index {idx}, {len(maps[c])} primitive cycles in {len(cos)} cosets; coset shares "
              + ", ".join(f"{t:.5f}" for t in tot))
        alone += [(c, ks[0][1], idx, rel[ks[0]]) for ks in cos.values() if len(ks) == 1]
    print(f"\n{nontrivial} maps with index > 1; cosets without a cycle: {empty if empty else 'none'}; "
          f"largest deviation of a coset share from 1/index: {worst:.1e}")
    print(f"{len(alone)} cycles alone in their coset (share exactly 1/index):")
    for c, mn, idx, s in alone:
        print(f"  3x+{c}, cycle {mn}: measured {s:.5f}, exact {1 / idx:.5f}")

    if pred_file:
        pred = {}
        for r in csv.DictReader(open(pred_file)):
            pred[(int(r["c"]), int(r["cycle_min"]))] = float(r["predicted"])
        groups = defaultdict(list)
        for k in pred:
            groups[k[0]].append(k)
        normed = {}
        for c, keys in groups.items():
            H, idx = structure(c)
            cos = defaultdict(list)
            for k in keys:
                cos[coset_of(k[1] % c, c, H)].append(k)
            for ks in cos.values():
                s = sum(pred[k] for k in ks)
                for k in ks:
                    normed[k] = pred[k] / s / idx if s > 0 else 0.0
        print("\nbackward-mass predictor:")
        print("  as computed           :", metrics(groups, rel, pred))
        print("  normalised in cosets  :", metrics(groups, rel, normed))


if __name__ == "__main__":
    main()
