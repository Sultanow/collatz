/*
 * mitm_census.cpp -- Run P (roadmap C2): census of the primitive cycles of all maps
 *
 *        T_{q,c}(x) = (q*x + c)/2   if x is odd,
 *        T_{q,c}(x) =  x/2          if x is even,        c odd, 1 <= |c| <= DMAX,
 *
 * by a meet-in-the-middle search over the parity words of one type (l,k) at a time.
 * Same output as census_all.c (Run A), which checks all 2^l words one by one.
 *
 * A word B of type (l,k) gives the periodic point c*z/D of T_{q,c}, where D = 2^l - q^k and
 * z = z_q(B) = sum_{j=1..k} q^(k-j) 2^(p_j) (p_j = positions of the ones). With A = |D| and
 * d0 = A/gcd(z,A), B yields a primitive cycle of T_{q,c0}, c0 = sign(D)*d0, and the census
 * keeps the words with d0 <= DMAX. Let S be the set of divisors of A that are <= DMAX. A word is
 * kept iff d0 lies in S, that is iff z = 0 (mod A/d*) for some maximal element d* of S.
 *
 * For each maximal d* the congruence z = 0 (mod M), M = A/d*, is solved by splitting
 * B = B1 B2 into halves of lengths h1 = floor(l/2) and h2 = l - h1 with k1 and k2 ones:
 *
 *        z(B) = q^(k2) z(B1) + 2^(h1) z(B2)        (half-word formula, Lemma 2(a) of the paper),
 *
 * so z(B) = 0 (mod M) iff u(B1) = v(B2) with u = q^(k2) z(B1) mod M, v = -2^(h1) z(B2) mod M.
 * Both lists are generated by a depth-first search with one modular addition per one-bit,
 * sorted by the low 64 bits of the residue and merged. Every match is checked exactly
 * (z in 128-bit arithmetic, d0 by continued fractions, one walk around the cycle as in
 * census_all.c), and only the rotation that starts at the smallest member of a primitive
 * cycle is printed. Work per type: about sum_{k1} (C(h1,k1) + C(h2,k2)), i.e. O(2^(l/2)),
 * instead of C(l,k). If the two lists of one split exceed the memory budget, the residues
 * are processed in 2^b passes by their top b key bits (lists regenerated per pass).
 *
 * Usage:   mitm_census q DMAX Lmin Lmax [kmin kmax] [--mem GB] [--cand N] [--lcap L]
 *          all types (l,k) with Lmin <= l <= Lmax and kmin <= k <= kmax (default 1..l).
 *          --mem: memory for the two lists of one pass and their sorted copies (default 4 GB).
 *          The maximal divisors d* are searched together, modulo A/L with L = lcm, as long as the
 *          expected number of exact checks C(l,k) L / A stays below --cand (default 0.1) times the
 *          number of residues one search generates, and
 *          L <= --lcap (default no limit; --lcap 1 gives one search per maximal divisor).
 *
 * Output:  one line per primitive cycle, exactly as census_all.c:
 *   c=<c0> min=<smallest member> l=<length> k=<odd steps> D=<2^l-q^k> word=<word from min>
 *          and one summary line per type:
 *   # q=.. DMAX=.. l=.. k=.. dstar=<maximal divisors> pairs=<key matches> words=<exact solutions>
 *     cycles=<printed> mismatches=<0> passes=<max> maxlist=<entries> rss_mb=<peak> seconds=<..>
 *
 * Limits:  l <= 70 for q = 3 (halves of at most 35 bits; all residues below 2^126; exact z and
 *          the cycle members in 128-bit arithmetic). Types outside the limits are reported with
 *          'skipped' and exit code 2.
 * Build:   g++ -O2 -std=c++17 -o mitm_census mitm_census.cpp
 */
#include <algorithm>
#include <chrono>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>

typedef __int128 i128;
typedef unsigned __int128 u128;

static long q, dmax;
static double mem_budget = 4.0e9;                 /* bytes for the two lists of one pass */
static long lcap = 4000000000000000000L;            /* upper limit for the lcm of one group (--lcap) */
static double cand_factor = 0.1;                    /* exact checks per group: C(l,k) L / A <= factor * residues */
static long long g_pairs, g_words, g_printed, g_mismatch;

static void print_i128(i128 v)
{
    char buf[64];
    int n = 0, neg = v < 0;
    u128 u = neg ? (u128)(-v) : (u128)v;
    do { buf[n++] = (char)('0' + (int)(u % 10)); u /= 10; } while (u);
    if (neg) putchar('-');
    while (n) putchar(buf[--n]);
}

static void sprint_u128(char *out, u128 u)
{
    char buf[64];
    int n = 0;
    do { buf[n++] = (char)('0' + (int)(u % 10)); u /= 10; } while (u);
    int i = 0;
    while (n) out[i++] = buf[--n];
    out[i] = 0;
}

/* denominator of r/A in lowest terms if it is <= dmax, else 0 (continued fractions; as census_all.c) */
static long small_denominator(u128 A, u128 r)
{
    if (r == 0) return 1;
    u128 a = A, b = r, kprev = 0, k = 1;
    while (b) {
        u128 t = a / b, rem = a % b;
        if (t > (u128)dmax) return 0;
        u128 knew = t * k + kprev;
        if (knew > (u128)dmax) return 0;
        kprev = k; k = knew;
        a = b; b = rem;
    }
    return (long)k;
}

static inline u128 addmod(u128 a, u128 b, u128 M)
{
    u128 s = a + b;
    return s >= M ? s - M : s;
}

/* exact z for the full word m (bit s = step s) */
static u128 z_exact(u128 m, int l)
{
    u128 z = 0, qp = 1;
    for (int p = l - 1; p >= 0; p--)
        if ((m >> p) & 1) { z += qp << p; qp *= (u128)q; }
    return z;
}

/* walk around the cycle of the word m: print it if m is the rotation starting at the smallest
   member of a primitive cycle (exactly the test of census_all.c) */
static void test_word(u128 m, int l, int k, i128 D, u128 A, u128 z, long d0)
{
    u128 x = z / (A / (u128)d0);                   /* exact: A/d0 divides z */
    i128 c0 = (D > 0) ? d0 : -d0;
    i128 y = (i128)x;
    for (int s = 0; s < l; s++) {
        if ((int)(y & 1) != (int)((m >> s) & 1)) { g_mismatch++; return; }
        y = (y & 1) ? ((i128)q * y + c0) / 2 : y / 2;
        if (s < l - 1) {
            if (y == (i128)x) return;               /* power of a shorter word */
            if (y < (i128)x) return;                /* not the rotation that starts at the minimum */
        }
    }
    if (y != (i128)x) { g_mismatch++; return; }
    g_printed++;
    printf("c="); print_i128(c0);
    printf(" min="); print_i128((i128)x);
    printf(" l=%d k=%d D=", l, k); print_i128(D);
    printf(" word=");
    for (int s = 0; s < l; s++) putchar(((m >> s) & 1) ? '1' : '0');
    putchar('\n');
}

struct Ent {
    uint64_t key;                                   /* low 64 bits of the residue */
    uint64_t mask;                                  /* half-word, bit p = position p of the half */
    bool operator<(const Ent &o) const { return key < o.key; }
};

struct Gen {
    int h, w, sign;                                 /* half length, ones, sign = +1 (u) or -1 (v) */
    u128 M;
    const std::vector<std::vector<u128>> *t;        /* t[j][p]: term of the j-th one at position p */
    int bits;                                       /* pass selection: top 'bits' key bits == pass */
    uint64_t pass;
    std::vector<Ent> *out;
    void rec(int pos, int left, int j, u128 acc, uint64_t mask)
    {
        if (left == 0) {
            u128 val = acc;
            if (sign < 0) val = acc ? M - acc : 0;
            uint64_t key = (uint64_t)val;
            if (bits == 0 || (key >> (64 - bits)) == pass) out->push_back({key, mask});
            return;
        }
        if (h - pos < left) return;
        /* one at pos */
        rec(pos + 1, left - 1, j + 1, addmod(acc, (*t)[j][pos], M), mask | (1ULL << pos));
        /* zero at pos */
        if (h - pos > left) rec(pos + 1, left, j, acc, mask);
    }
};

/* peak resident memory of the process in MB (Linux), 0 if unknown */
static long peak_rss_mb()
{
    FILE *f = fopen("/proc/self/status", "r");
    if (!f) return 0;
    char line[256];
    long kb = 0;
    while (fgets(line, sizeof line, f))
        if (!strncmp(line, "VmHWM:", 6)) { kb = atol(line + 6); break; }
    fclose(f);
    return kb / 1024;
}

static double binom(int n, int r)
{
    if (r < 0 || r > n) return 0;
    double b = 1;
    for (int i = 1; i <= r; i++) b = b * (n - r + i) / i;
    return b;
}

/* bucketed join of U and V on the key: one counting scatter by the top bits, then small sorts */
template <class F>
static void join(std::vector<Ent> &U, std::vector<Ent> &V, int skip, F &&onmatch)
{
    size_t n = std::max(U.size(), V.size());
    int B = 0;
    while (B < 20 && ((size_t)256 << B) < n) B++;
    if (B == 0) {
        std::sort(U.begin(), U.end());
        std::sort(V.begin(), V.end());
    }
    std::vector<size_t> cu((1u << B) + 1, 0), cv((1u << B) + 1, 0);
    std::vector<Ent> U2, V2;
    auto bucket = [&](uint64_t key) -> size_t { return B ? (size_t)((key << skip) >> (64 - B)) : 0; };
    if (B > 0) {
        for (auto &e : U) cu[bucket(e.key) + 1]++;
        for (auto &e : V) cv[bucket(e.key) + 1]++;
        for (size_t b = 0; b < ((size_t)1 << B); b++) { cu[b + 1] += cu[b]; cv[b + 1] += cv[b]; }
        U2.resize(U.size());
        V2.resize(V.size());
        {
            std::vector<size_t> pu(cu.begin(), cu.end() - 1), pv(cv.begin(), cv.end() - 1);
            for (auto &e : U) U2[pu[bucket(e.key)]++] = e;
            for (auto &e : V) V2[pv[bucket(e.key)]++] = e;
        }
        std::vector<Ent>().swap(U);
        std::vector<Ent>().swap(V);
    } else {
        U2.swap(U);
        V2.swap(V);
        cu[1] = U2.size();
        cv[1] = V2.size();
    }
    for (size_t b = 0; b < ((size_t)1 << B); b++) {
        Ent *u0 = U2.data() + cu[b], *u1 = U2.data() + cu[b + 1];
        Ent *v0 = V2.data() + cv[b], *v1 = V2.data() + cv[b + 1];
        if (u0 == u1 || v0 == v1) continue;
        if (B) { std::sort(u0, u1); std::sort(v0, v1); }
        Ent *i = u0, *j = v0;
        while (i < u1 && j < v1) {
            if (i->key < j->key) { i++; continue; }
            if (i->key > j->key) { j++; continue; }
            Ent *i2 = i, *j2 = j;
            while (i2 < u1 && i2->key == i->key) i2++;
            while (j2 < v1 && j2->key == j->key) j2++;
            for (Ent *a = i; a < i2; a++)
                for (Ent *b2 = j; b2 < j2; b2++) onmatch(*a, *b2);
            i = i2; j = j2;
        }
    }
}

/* all words of type (l,k) with z = 0 mod M, M = A/L, L = lcm of the group 'which' of maximal divisors */
static void solve(int l, int k, i128 D, u128 A, const std::vector<std::vector<long>> &groups, int which,
                  int &maxpasses, double &maxlist)
{
    long L = 1;
    for (long d : groups[which]) L = L / std::__gcd(L, d) * d;
    u128 M = A / (u128)L;
    int h1 = l / 2, h2 = l - h1;
    /* q^e mod M */
    std::vector<u128> qpow(k + 1);
    qpow[0] = 1 % M;
    for (int e = 1; e <= k; e++) {
        u128 s = 0;
        for (long i = 0; i < q; i++) s = addmod(s, qpow[e - 1], M);
        qpow[e] = s;
    }
    for (int k1 = std::max(0, k - h2); k1 <= std::min(k, h1); k1++) {
        int k2 = k - k1;
        /* term tables: side 1, j-th one overall (j = 0..k1-1 here, i.e. exponent k-1-j) at position p;
           side 2, i-th one of B2 (exponent k2-1-i) at position h1+p */
        std::vector<std::vector<u128>> t1(k1, std::vector<u128>(h1)), t2(k2, std::vector<u128>(h2));
        for (int j = 0; j < k1; j++) {
            u128 v = qpow[k - 1 - j];
            for (int p = 0; p < h1; p++) { t1[j][p] = v; v = addmod(v, v, M); }
        }
        for (int i = 0; i < k2; i++) {
            u128 v = qpow[k2 - 1 - i];
            for (int p = 0; p < h1; p++) v = addmod(v, v, M);
            for (int p = 0; p < h2; p++) { t2[i][p] = v; v = addmod(v, v, M); }
        }
        double n1 = binom(h1, k1), n2 = binom(h2, k2);
        int bits = 0;
        /* peak memory of one pass: both lists and their scattered copies */
        while (2.0 * (n1 + n2) * sizeof(Ent) / (double)(1ULL << bits) > mem_budget && bits < 20) bits++;
        int passes = 1 << bits;
        maxpasses = std::max(maxpasses, passes);
        maxlist = std::max(maxlist, std::max(n1, n2));
        for (uint64_t pass = 0; pass < (uint64_t)passes; pass++) {
            std::vector<Ent> U, V;
            U.reserve((size_t)(n1 / passes * 1.05) + 64);
            V.reserve((size_t)(n2 / passes * 1.05) + 64);
            Gen g1{h1, k1, +1, M, &t1, bits, pass, &U};
            Gen g2{h2, k2, -1, M, &t2, bits, pass, &V};
            g1.rec(0, k1, 0, 0, 0);
            g2.rec(0, k2, 0, 0, 0);
            join(U, V, bits, [&](const Ent &a, const Ent &b) {
                g_pairs++;
                u128 m = (u128)a.mask | ((u128)b.mask << h1);
                u128 z = z_exact(m, l);
                long d0 = small_denominator(A, z % A);
                if (!d0 || L % d0) return;                 /* key collision, or d0 > DMAX */
                int first = -1;                            /* report in the first group that covers d0 */
                for (int g = 0; g < (int)groups.size() && first < 0; g++)
                    for (long d : groups[g])
                        if (d % d0 == 0) { first = g; break; }
                if (first != which) return;
                g_words++;
                test_word(m, l, k, D, A, z, d0);
            });
        }
    }
}

int main(int argc, char **argv)
{
    std::vector<char *> pos;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--mem") && i + 1 < argc) { mem_budget = atof(argv[++i]) * 1e9; continue; }
        if (!strcmp(argv[i], "--lcap") && i + 1 < argc) { lcap = atol(argv[++i]); continue; }
        if (!strcmp(argv[i], "--cand") && i + 1 < argc) { cand_factor = atof(argv[++i]); continue; }
        pos.push_back(argv[i]);
    }
    if (pos.size() != 4 && pos.size() != 6) {
        fprintf(stderr, "usage: %s q DMAX Lmin Lmax [kmin kmax] [--mem GB]\n", argv[0]);
        return 1;
    }
    q = atol(pos[0]);
    dmax = atol(pos[1]);
    int Lmin = atoi(pos[2]), Lmax = atoi(pos[3]);
    int kmin = pos.size() == 6 ? atoi(pos[4]) : 1, kmax = pos.size() == 6 ? atoi(pos[5]) : 1000;
    if (q < 3 || q % 2 == 0 || q > 15) { fprintf(stderr, "q must be odd, 3 <= q <= 15\n"); return 1; }
    if (dmax < 1 || dmax > 1000000) { fprintf(stderr, "need 1 <= DMAX <= 10^6\n"); return 1; }
    if (Lmin < 1 || Lmax > 70 || Lmin > Lmax) { fprintf(stderr, "need 1 <= Lmin <= Lmax <= 70\n"); return 1; }
    double lq = log2((double)q);
    int rc = 0;
    for (int l = Lmin; l <= Lmax; l++) {
        for (int k = std::max(1, kmin); k <= std::min(l, kmax); k++) {
            auto t0 = std::chrono::steady_clock::now();
            /* limits: residues below 2^126, exact z and the members (times q, plus c) in 128 bits */
            double zbits = (l - k) + k * lq;
            if (std::max((double)l, k * lq) > 125.0 || zbits > 125.0 || log2((double)dmax) + zbits + lq + 2 > 126.0) {
                printf("# q=%ld DMAX=%ld l=%d k=%d skipped (128-bit limits)\n", q, dmax, l, k);
                rc = 2;
                continue;
            }
            u128 qk = 1;
            for (int e = 0; e < k; e++) qk *= (u128)q;
            i128 D = (i128)(((u128)1) << l) - (i128)qk;
            if (D == 0) continue;
            u128 A = D > 0 ? (u128)D : (u128)(-D);
            /* divisors of A up to DMAX, and the maximal ones */
            std::vector<long> S, dstar;
            for (long d = 1; d <= dmax; d++)
                if (A % (u128)d == 0) S.push_back(d);
            for (long d : S) {
                bool maximal = true;
                for (long e : S)
                    if (e != d && e % d == 0) { maximal = false; break; }
                if (maximal) dstar.push_back(d);
            }
            std::sort(dstar.begin(), dstar.end(), [](long a, long b) { return a > b; });
            /* group them greedily while the lcm L stays small enough: the search modulo A/L costs the
               same, and the expected number of exact checks is C(l,k) L / A */
            std::vector<std::vector<long>> groups;
            {
                double work = 0;                           /* residues generated by one search */
                for (int k1 = std::max(0, k - (l - l / 2)); k1 <= std::min(k, l / 2); k1++)
                    work += binom(l / 2, k1) + binom(l - l / 2, k - k1);
                double cap = cand_factor * work * (double)A / binom(l, k);
                long lc = cap >= (double)lcap ? lcap : (long)std::max(1.0, cap);
                std::vector<long> L;
                for (long d : dstar) {
                    bool placed = false;
                    for (size_t g = 0; g < groups.size() && !placed; g++) {
                        long nl = L[g] / std::__gcd(L[g], d);
                        if (nl <= lc / d) { groups[g].push_back(d); L[g] = nl * d; placed = true; }
                    }
                    if (!placed) { groups.push_back({d}); L.push_back(d); }
                }
            }
            long long p0 = g_pairs, w0 = g_words, c0 = g_printed, m0 = g_mismatch;
            int maxpasses = 1;
            double maxlist = 0;
            for (int w = 0; w < (int)groups.size(); w++) solve(l, k, D, A, groups, w, maxpasses, maxlist);
            double sec = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
            char dbuf[64];
            sprint_u128(dbuf, A);
            printf("# q=%ld DMAX=%ld l=%d k=%d D=%s%s dstar=", q, dmax, l, k, D < 0 ? "-" : "", dbuf);
            for (size_t w = 0; w < dstar.size(); w++) printf("%s%ld", w ? "," : "", dstar[w]);
            printf(" groups=%zu pairs=%lld words=%lld cycles=%lld mismatches=%lld passes=%d maxlist=%.0f rss_mb=%ld seconds=%.3f\n",
                   groups.size(), g_pairs - p0, g_words - w0, g_printed - c0, g_mismatch - m0, maxpasses, maxlist, peak_rss_mb(), sec);
            fflush(stdout);
        }
    }
    if (g_mismatch) return 3;
    return rc;
}
